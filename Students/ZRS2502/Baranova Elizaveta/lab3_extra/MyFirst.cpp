	void calc(double x, double y) {
		ofstream file("results.txt"); // открываем текстовый файл
		double t;
		int k, l, m, n;
		t = cos(M_PI / 7) * (pow(sin(x - 8 * y), 2) / 2.7 * (x - M_PI));
		k = t; // Неявное преобразование в целый тип с усечением
		l = int(t); // Явное преобразование в целый тип с усечением в стиле С (способ 1)
		m = ceil(t); // Неявное преобразование в целый тип с округлением в большую сторону
		n = floor(t); // Неявное преобразование в целый тип с округлением в меньшую сторону
		cout << endl << "Вещественное t= " << t;
		cout << endl << "Целая часть результата (неявно) k= " << k;
		cout << endl << "Целая часть результата (неявно) l= " << l;
		cout << endl << "Округленное в большую сторону m= " << m;
		cout << endl << "Округленное в меньшую сторону n= " << n << endl;
		cout << endl << "Значение префиксного инкремента ++k= " << ++k;
		cout << endl << "Значение постфиксного инкремента l++= " << l++;
		cout << endl << "Значение k после приращения = " << k;
		cout << endl << "Значение l после приращения = " << l << endl << endl;
		// запись в текстовый файл
		file << "Вещественное t= " << t;
		file << endl << "Целая часть результата (неявно) k= " << k;
		file << endl << "Целая часть результата (неявно) l= " << l;
		file << endl << "Округленное в большую сторону m= " << m;
		file << endl << "Округленное в меньшую сторону n= " << n << endl;
		file << endl << "Значение префиксного инкремента ++k= " << ++k;
		file << endl << "Значение постфиксного инкремента l++= " << l++;
		file << endl << "Значение k после приращения = " << k;
		file << endl << "Значение l после приращения = " << l << endl << endl;
		file.close(); // закрываем текстовый файл
	}